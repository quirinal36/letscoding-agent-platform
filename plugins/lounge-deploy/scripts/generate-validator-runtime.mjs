import { cp, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, URL } from "node:url";

const pluginRoot = fileURLToPath(new URL("../", import.meta.url));
const repositoryRoot = fileURLToPath(new URL("../../../", import.meta.url));
const runtimeRoot = fileURLToPath(new URL("../runtime/", import.meta.url));
const policyRequire = createRequire(
  `${repositoryRoot}packages/policy-contract/package.json`,
);

await rm(runtimeRoot, { recursive: true, force: true });
await copyJavaScript(
  `${repositoryRoot}packages/artifact-validator/dist`,
  `${runtimeRoot}artifact-validator`,
);
await copyJavaScript(
  `${repositoryRoot}packages/policy-contract/dist`,
  `${runtimeRoot}node_modules/@letscoding/policy-contract`,
);
await writeFile(
  `${runtimeRoot}node_modules/@letscoding/policy-contract/package.json`,
  `${JSON.stringify(
    {
      name: "@letscoding/policy-contract",
      private: true,
      type: "module",
      exports: {
        ".": "./index.js",
        "./node": "./node.js",
      },
    },
    null,
    2,
  )}\n`,
  "utf8",
);
const ajvRequire = createRequire(policyRequire.resolve("ajv/package.json"));
for (const [packageName, resolver] of [
  ["ajv", policyRequire],
  ["ajv-formats", policyRequire],
  ["fast-deep-equal", ajvRequire],
  ["fast-uri", ajvRequire],
  ["json-schema-traverse", ajvRequire],
  ["require-from-string", ajvRequire],
]) {
  const source = dirname(resolver.resolve(`${packageName}/package.json`));
  await cp(source, `${runtimeRoot}node_modules/${packageName}`, {
    recursive: true,
    dereference: true,
  });
}
await writeFile(
  `${runtimeRoot}README.md`,
  "Generated by scripts/generate-validator-runtime.mjs. Do not edit by hand.\n",
  "utf8",
);

process.stdout.write(
  `Generated bundled validator runtime in ${pluginRoot}runtime\n`,
);

async function copyJavaScript(source, destination) {
  await mkdir(destination, { recursive: true });
  for (const entry of await readdir(source, { withFileTypes: true })) {
    const sourcePath = `${source}/${entry.name}`;
    const destinationPath = `${destination}/${entry.name}`;
    if (entry.isDirectory()) {
      await copyJavaScript(sourcePath, destinationPath);
    } else if (entry.isFile() && entry.name.endsWith(".js")) {
      await cp(sourcePath, destinationPath);
    }
  }
}
